type LeafPaths<T> = T extends readonly unknown[]
  ? never
  : {
      [K in keyof T & string]: T[K] extends string
        ? K
        : T[K] extends readonly unknown[]
          ? never
          : T[K] extends object
            ? `${K}.${LeafPaths<T[K]>}`
            : never;
    }[keyof T & string];

export type TranslationKey = LeafPaths<Dictionary>;
